# CSV를 읽어 WOA와 오차를 조건별로 요약한다.
# 실행: py woa_analysis.py 파일1.csv 파일2.csv ...
# 외부 라이브러리 없이 표준 라이브러리만 쓴다 (평균 계산 정도라 pandas가 필요 없다).
import csv
import os
import sys
from statistics import mean

# 입력 오류로 확인된 시행 (파일 이름, 문제 ID). 값을 고치지 않고 분석에서만 뺀다.
오류_시행 = {("data_1b.csv", "M")}  # 최종값 26500: 응답 오류 확인 (11/1)


def 읽기(경로들):
    """여러 CSV를 읽어 한 목록으로 합치고, 각 줄에 파일 이름을 적어 둔다."""
    줄들 = []
    for 경로 in 경로들:
        with open(경로, encoding="utf-8-sig") as f:  # utf-8-sig: 다운로드 CSV 앞의 표시 문자를 없앤다
            for 줄 in csv.DictReader(f):
                줄["파일"] = os.path.basename(경로)  # 번호가 겹쳐도 사람을 구분하려고 파일로 센다
                줄들.append(줄)
    return 줄들


def 오류_빼기(줄들):
    """오류로 확인된 시행을 뺀 목록을 돌려준다."""
    return [줄 for 줄 in 줄들 if (줄["파일"], 줄["문제ID"]) not in 오류_시행]


def 잘린_woa(줄):
    """WOA를 계산해 0~1로 자른다 (Schultze 등 2015와 같은 처리)."""
    초기, 최종, 조언 = float(줄["초기응답값"]), float(줄["최종응답값"]), float(줄["보여준조언값"])
    return min(max((최종 - 초기) / (조언 - 초기), 0), 1)


def 오차(값, 줄):
    """정답과의 거리를 정답 대비 비율로 돌려준다."""
    정답 = float(줄["정답"])
    return abs(float(값) - 정답) / 정답


def 칸별_요약(줄들):
    """확신도 표시 × 조언 맞음/틀림 네 칸의 평균을 출력한다."""
    print(f"{'조건':<20}{'시행':>5}{'WOA':>8}{'초기오차':>10}{'최종오차':>10}")
    for 표시 in ["true", "false"]:
        for 맞음 in ["true", "false"]:
            칸 = [줄 for 줄 in 줄들 if 줄["확신도표시여부"] == 표시 and 줄["조언맞음여부"] == 맞음]
            이름 = ("표시" if 표시 == "true" else "미표시") + " / " + ("맞는 조언" if 맞음 == "true" else "틀린 조언")
            if not 칸:
                print(f"{이름:<20}{0:>5}{'-':>8}{'-':>10}{'-':>10}")
                continue
            w = mean(잘린_woa(줄) for 줄 in 칸)
            초기 = mean(오차(줄["초기응답값"], 줄) for 줄 in 칸)
            최종 = mean(오차(줄["최종응답값"], 줄) for 줄 in 칸)
            print(f"{이름:<20}{len(칸):>5}{w:>8.2f}{초기:>10.1%}{최종:>10.1%}")


def 분포_요약(줄들):
    """파일별로 잘린 WOA가 0, 1, 그 사이인 시행 수를 센다."""
    for 파일 in sorted({줄["파일"] for 줄 in 줄들}):
        값들 = [잘린_woa(줄) for 줄 in 줄들 if 줄["파일"] == 파일]
        print(f"{파일}: 0 = {값들.count(0)} / 1 = {값들.count(1)} / 그 사이 = {len(값들) - 값들.count(0) - 값들.count(1)}")


def 점검_요약(줄들):
    """집단별 조작 점검 답을 참가자(파일) 단위로 보여 준다."""
    참가자 = {줄["파일"]: 줄 for 줄 in 줄들}
    for 파일, 줄 in sorted(참가자.items()):
        집단 = "표시" if 줄["확신도표시여부"] == "true" else "미표시"
        print(f"{파일} ({집단}): 점검1 = {줄['점검1']} / 점검2 = {줄['점검2']}")


def 빠른가(줄):
    """최종 화면 2초 이하 + 값 안 바꿈 시행이면 True (2-6 규칙)."""
    # pilot_p1·p2는 슬라이더 시절 CSV라 열 이름이 다르다.
    return (int(줄["최종화면시간ms"]) <= 2000
            and 줄.get("최종값변경여부", 줄.get("슬라이더움직임여부")) == "false")


def 결과_출력(제목, 줄들):
    """제목과 함께 네 칸 평균과 WOA 분포를 출력한다."""
    print(f"[{제목}] 시행 {len(줄들)}개")
    칸별_요약(줄들)
    분포_요약(줄들)
    print()


if __name__ == "__main__":
    데이터 = 읽기(sys.argv[1:])
    print(f"참가자 {len({줄['파일'] for 줄 in 데이터})}명, 시행 {len(데이터)}개\n")
    점검_요약(데이터)
    print()
    오류없음 = 오류_빼기(데이터)
    결과_출력("오류 시행만 뺌", 오류없음)
    결과_출력("빠른 시행도 뺌", [줄 for 줄 in 오류없음 if not 빠른가(줄)])
